/**
 * 限速的桶名：**一个人一个桶**，而 IPv6 下「一个地址」不等于「一个人」。
 *
 *   node scripts/check-ratelimit-bucket.mjs
 *
 * ── 为什么要一道门 ────────────────────────────────────────────
 *
 * `api/_ratelimit.js` 的 `callerId` 从前直接把头里拿到的字符串当桶名。IPv4 时代那是对的：
 * 一条宽带一个地址，换地址要么重拨要么买代理，都有成本，所以「一小时 10 次」真的是一小时
 * 10 次。
 *
 * IPv6 下这个前提整个没了。家宽标配分到的是一整个 /64（1.8×10¹⁹ 个地址），而且是自己随便
 * 用的：换一个源地址不用重拨、不用代理、不花一分钱。于是注册、兑码、换邮箱那几道
 * `tooMany` 全部变成摆设——**而限速那一侧看着在工作**（日志里确实有键在涨）。Vercel 的边缘
 * 默认就给 IPv6 客户端写 IPv6 的 `x-forwarded-for`，所以这不是理论上的。
 *
 * 2026-10-02 收到 /64。这道门钉住两件事：**该归并的归并**（同一个 /64、带端口、带 zone、
 * IPv4 映射地址），以及**不该归并的不许归并**（不同 /64、认不出来的东西原样留着）。后半同
 * 样要紧：把所有人归进同一个桶比不限速更糟，因为它看起来还在工作。
 *
 * 纯函数、不连库、几毫秒。端到端那一面在 `check-register.mjs` 的 ⑦（真起服务器，打真请求）。
 */
import { callerId } from '../api/_ratelimit.js';

let fail = 0;
const check = (n, ok, extra = '') => {
  console.log(`${ok ? 'PASS' : 'FAIL'}  ${n}${extra ? '  ' + extra : ''}`);
  if (!ok) fail++;
};

const bucket = (fwd, header = 'x-forwarded-for') => callerId({ headers: { [header]: fwd } });

// ── ① 认得出来的那些，归到什么桶 ────────────────────────────────
const TABLE = [
  // [头里的内容, 桶名, 这一条在说什么]
  ['1.2.3.4', '1.2.3.4', 'IPv4 原样'],
  ['1.2.3.4:443', '1.2.3.4', '带端口的 IPv4：端口不算身份'],
  ['  1.2.3.4  ', '1.2.3.4', '前后空白剥掉'],
  ['1.2.3.4, 10.0.0.1', '1.2.3.4', '只认第一段（Vercel 是覆写模型）'],
  ['::ffff:1.2.3.4', '1.2.3.4', 'IPv4 映射地址拆回 IPv4'],
  ['::ffff:102:304', '1.2.3.4', '同一个地址的十六进制写法，归同一个桶'],
  ['[::ffff:1.2.3.4]:443', '1.2.3.4', '映射地址 + 方括号 + 端口'],
  ['2001:db8:1:2:3:4:5:6', '2001:db8:1:2::/64', 'IPv6 收到 /64'],
  ['2001:db8:1:2:aaaa:bbbb:cccc:dddd', '2001:db8:1:2::/64', '同一个 /64 里的另一个地址'],
  ['2001:DB8:1:2::9', '2001:db8:1:2::/64', '大小写不算两个人'],
  ['[2001:db8:1:2::9]:54321', '2001:db8:1:2::/64', '方括号和端口剥掉'],
  ['2001:db8:1:2::9%eth0', '2001:db8:1:2::/64', 'zone 不算身份'],
  ['2001:db8::1', '2001:db8:0:0::/64', '压缩写法展开'],
  ['2001:db8::1.2.3.4', '2001:db8:0:0::/64', '末尾嵌一个 IPv4（少见但合法）'],
  ['::1', '0:0:0:0::/64', '本机'],
  // 认不出来的：原样留着，绝不悄悄归并。
  ['unknown', 'unknown', '认不出来的原样（本地起服务器就是这个）'],
  ['not:an:ip', 'not:an:ip', '看着像 IPv6 但解不开 → 原样'],
  ['2001:db8:1:2:3:4:5:6:7', '2001:db8:1:2:3:4:5:6:7', '九组 → 解不开 → 原样'],
  ['2001::db8::1', '2001::db8::1', '两个 :: → 解不开 → 原样'],
  ['2001:db8:1:2:3:4:5:zzzz', '2001:db8:1:2:3:4:5:zzzz', '非十六进制 → 原样'],
];
for (const [input, want, why] of TABLE) {
  const got = bucket(input);
  check(`① ${why}：${JSON.stringify(input)} → ${want}`, got === want, got === want ? '' : `实际 ${got}`);
}

// ── ② 不同的 /64 必须是不同的桶 ─────────────────────────────────
//
// 这是 ① 的反面，也是整道门的要害：收得太粗会把整个小区、整家运营商归进一个桶。
{
  const pairs = [
    ['2001:db8:1:2::1', '2001:db8:1:3::1', '第四组差一位 → 两个 /64'],
    ['2001:db8:1:2::1', '2001:db8:2:2::1', '第三组差一位'],
    ['2001:db8:1:2::1', '2001:db9:1:2::1', '第二组差一位'],
    ['2001:db8:1:2::1', '2002:db8:1:2::1', '第一组差一位'],
  ];
  for (const [a, b, why] of pairs) {
    check(`② ${why}`, bucket(a) !== bucket(b), `${bucket(a)} vs ${bucket(b)}`);
  }
  // 而同一个 /64 里后 64 位全不一样的两个地址必须是同一个桶（① 已经各量过一次，这儿
  // 直接比两个，省得有人把表里两行改成同一个值而不自知）。
  check('② 同一个 /64 里的两个地址是同一个桶',
    bucket('2001:db8:7:7::1') === bucket('2001:db8:7:7:ffff:ffff:ffff:ffff'),
    bucket('2001:db8:7:7::1'));
  // IPv4 一个地址一个桶，不许也被收粗了。
  check('② IPv4 相邻地址仍是两个桶', bucket('1.2.3.4') !== bucket('1.2.3.5'));
}

// ── ③ 读哪个头，按什么顺序 ──────────────────────────────────────
//
// `x-vercel-forwarded-for` 排在前面，理由不是「今天更安全」而是「将来还安全」：哪天前面挂
// 一层 CDN，`x-forwarded-for` 就可能被那一层改写，而前者是边缘自己写的、始终作数。
{
  const both = callerId({
    headers: { 'x-vercel-forwarded-for': '9.9.9.9', 'x-forwarded-for': '1.1.1.1' },
  });
  check('③ 两个头都在时，认 x-vercel-forwarded-for', both === '9.9.9.9', both);
  check('③ 只有 x-forwarded-for 时认它', bucket('1.1.1.1') === '1.1.1.1');
  check('③ 两个都没有时退到 x-real-ip，而且照样收 /64',
    bucket('2001:db8:5:5::1', 'x-real-ip') === '2001:db8:5:5::/64',
    bucket('2001:db8:5:5::1', 'x-real-ip'));
  check('③ 什么都没有 → unknown', callerId({ headers: {} }) === 'unknown');
  check('③ 压根没有 req 也不炸', callerId(undefined) === 'unknown');
  check('③ 空字符串 → unknown（不是空桶名）', bucket('') === 'unknown');
  check('③ 只有逗号空白 → unknown', bucket(' , ') === 'unknown');
}

console.log(fail ? `\n${fail} 条红` : '\n全绿');
process.exit(fail ? 1 : 0);
