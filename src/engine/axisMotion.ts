/**
 * 主菜单那条轴的**运动学**：追赶、橡皮筋、速度倾斜。
 *
 * 全是纯函数，一个 DOM 都不碰——所以 scripts/check-axis-motion.mjs 能拿 node
 * 直接跑，几十毫秒，进 CI。ui/modeAxis.ts 只管把手势和像素喂进来。
 *
 * ──────────────────────────────────────────────────────────────────
 * 为什么追赶不能写成「每帧走完剩下的 0.1」
 *
 * 那是最常见的写法（`x += (target - x) * 0.1`），也是最常见的坑：它是**按帧**
 * 算的，不是按时间算的。同样 100ms 的真实时间，帧数不同，追到的地方差很远：
 *
 *     帧率      100ms 里的帧数    每帧 0.1 追完的比例
 *     ─────────────────────────────────────────────
 *     30Hz      3                 27.1%
 *     60Hz      6                 46.9%
 *     120Hz     12                71.8%     ← 比 60Hz 快 1.5 倍
 *
 * 也就是说：开发机（60Hz）上调好的那一点「慢半拍」，到 iPhone 低电量模式
 * （30Hz）会变成「拖泥带水」，到 120Hz 的机器上会变成「几乎不慢」。屏幕上什么
 * 都不会红，只是每台机器手感不一样——和 PR-0 里弹簧那个写死 16.7ms 的毛病同一
 * 类，所以一次性按时间算清楚。
 *
 * 下面 damp() 用的是指数衰减：`1 − e^(−λ·dt)`。λ 由 AXIS_LERP 反推，使得
 * **60Hz 下每帧正好等于 0.1**（上表那一行一个数都不变），换到 30Hz / 120Hz
 * 也还是同样的 46.9%。
 */

/**
 * 每帧追赶的强度，按「60Hz 下每帧走完剩下的多少」来标。
 *
 * 0.1 是 Lenis 的默认值——玩家点名参照的就是它（「拖动中始终慢半拍、恒定、
 * 可预期」）。内容页那层阻尼（engine/smoothScroll.ts）用的也是这个数，两边
 * 手感一致。
 */
export const AXIS_LERP = 0.1;

/** 换算成按时间计的衰减率（1/秒）。60Hz 下正好等于 AXIS_LERP，换到别的帧率也不走样。 */
export const AXIS_LAMBDA = -Math.log(1 - AXIS_LERP) * 60;

/**
 * 手指**停住之后**的追赶强度（AXIS_LAMBDA 的 8 倍，时间常数约 20ms）。
 *
 * 「慢半拍」是给**正在动**的那一刻的。手指已经停下来不动了还慢半拍，就变成另一
 * 件事：玩家停住、等一下、松手，轴却又自己往前滑过两张——那正是他早先点名修掉
 * 的「凭空跳一格」（门：check-mode-axis 的「停下来再松手，就停在眼睛看着的那一
 * 项」）。实测过：只按 AXIS_LERP 追，停住 150ms 只追回 61%，松手那一刻画面在
 * 4.92、落点在 7，差两张卡。
 *
 * 所以停住就把画面追齐。「停住」沿用 FLING_STALE（80ms，和「这是放下、不是甩出
 * 去」同一个阈值，不另立一个数）；追齐大约再要 60ms，眼睛看到的是「跟上来了」，
 * 不是「跳了一下」——而且那会儿画面本来就在减速，接上去是顺的。
 */
export const AXIS_SETTLE_LAMBDA = AXIS_LAMBDA * 8;

/**
 * 从 current 往 target 追 dtMs 毫秒。**帧率无关。**
 *
 * dt 的上限和 engine/spring.ts 同一个数（64ms）：切到后台再回来那一下 dt 可能
 * 是好几秒，不截断的话一帧就贴到目标上，看着像「跳了一下」。
 */
export function damp(current: number, target: number, dtMs: number, lambda = AXIS_LAMBDA): number {
  const dt = Math.min(Math.max(dtMs, 0), 64);
  return current + (target - current) * (1 - Math.exp((-lambda * dt) / 1000));
}
