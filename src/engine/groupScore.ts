import type { Cell, Tile } from './types';

/**
 * 一组图案值几分——**全站只有这一处**。
 *
 * 这条规则原先是 `Math.max(4, region.length)`，八副棋盘里各自抄了一遍，一共
 * 十六处。《星星跟随色块消除》要给星星单独一套算法，十六处各改一遍必漏，所以
 * 先收成这一个函数；`scripts/check-star-score.mjs` 会静态扫一遍，谁再往棋盘里
 * 抄一份 `Math.max(4, …)` 就当场红。
 *
 * ── 规则（玩家拍板的「乙」案）────────────────────────────────────────────
 *
 *   色块那部分照旧：min 4 分，超过 4 枚按枚数给
 *   星星那部分按平方：|S|²
 *   两部分相加
 *
 *     一组里有色块  →  max(4, 色块枚数) + 星星枚数²
 *     一组全是星星  →  星星枚数²          （色块那部分是 0，不是 4）
 *
 * 举几个数（这几个就是那道门钉住的）：
 *
 *   ● ● ● ●        4 色块      max(4,4) + 0  =  4     和从前一模一样
 *   ● ● ● ● ● ●    6 色块      max(4,6) + 0  =  6     和从前一模一样
 *   ★ ★ ★ ★ ★    5 星星      0 + 5²        = 25     玩家点名的那个例子
 *   ★ ★ ★ ★      4 星星      0 + 4²        = 16
 *   ● ● ★ ★ ★    2 色 3 星   max(4,2) + 3² = 13
 *   ● ★ ★ ★ ★    1 色 4 星   max(4,1) + 4² = 20
 *
 * ── 为什么「全是星星」那一路色块部分给 0 而不是 4 ──────────────────────
 *
 * `max(4, 0)` 是 4，照字面写下去，5 颗星星会算成 4 + 25 = 29。可玩家确认过的
 * 数是 **25**。那个 4 是「能得分的最小图案就是 4 格」的地板，说的是整组，不是
 * 说色块——一组里没有色块的时候，色块那部分就该是 0 分。
 *
 * ── 另外两种读法为什么没选 ──────────────────────────────────────────────
 *
 * 「甲」= 地板算在整组头上（`max(4, 总枚数) − |S| + |S|²`），同样满足 25 和 4
 * 那两个端点，混合那一格算出 11 而不是 13。玩家挑了给得更爽的乙。
 *
 * 「丙」= 只要组里有一颗星星，整组一起平方。这条被否掉是因为它有断崖和刷分
 * 口：`●●●★`（3 色块 + 1 星星）会从 4 分跳到 16 分，于是玩家只要往任何图案里
 * 塞进一颗星星，分就翻四倍。乙没有断崖——多一颗星星只多 `2|S|−1` 分。
 *
 * ── 这个函数不管老虎机那套 ──────────────────────────────────────────────
 *
 * 老虎机模式（targets）的图案分是 `targets.ts` 的 `scoreOf`（`ceil(n²/2)`），
 * 走的是另一条路，这里一个字都不碰。
 */

/** 能得分的最小图案就是 4 格（1×4、2+2、1-2-1），所以 4 是色块那部分的地板。 */
export const MIN_GROUP_POINTS = 4;

/**
 * @param cells  这一组的全部格子
 * @param tileAt 拿某一格上的棋子；拿不到（越界、空位）按「不是星星」算
 */
export function groupPoints(
  cells: Cell[],
  tileAt: (r: number, c: number) => Tile | null | undefined,
): number {
  let stars = 0;
  for (const [r, c] of cells) {
    // 'dot' 就是界面上那颗星星（消过一次、翻过来的那一面）。'flavor' 是色块。
    if (tileAt(r, c)?.face === 'dot') stars++;
  }
  const blocks = cells.length - stars;
  const blockPart = blocks > 0 ? Math.max(MIN_GROUP_POINTS, blocks) : 0;
  return blockPart + stars * stars;
}
