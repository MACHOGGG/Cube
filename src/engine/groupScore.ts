import type { Cell, Tile } from './types';

/**
 * 一组图案值几分——**全站只有这一处**。
 *
 * 这条规则原先是 `Math.max(4, region.length)`，八副棋盘里各自抄了一遍，一共
 * 十六处。《星星跟随色块消除》要给星星单独一套算法，十六处各改一遍必漏，所以
 * 先收成这一个函数；`scripts/check-star-score.mjs` 会静态扫一遍，谁再往棋盘里
 * 抄一份 `Math.max(4, …)` 就当场红。
 *
 * ── 规则（玩家给的最终版）──────────────────────────────────────────────
 *
 *   一组里有色块  →  max(4, 整组枚数)   ← 和从前**完全一样**，一个数都没变
 *   一组全是星星  →  星星枚数²
 *
 * 就是说：**混合组什么都不变**。星星混在色块的图案里，既不多算分、也不消除；
 * 消除的还是原来那件事——色块翻成星星，星星留在原地。只有「整组都是星星」这一
 * 种是新的：按星星枚数平方给分，而且那一批星星**从棋盘上消除**（所以同一批星星
 * 凑不回同一个形状，不需要另记一本防刷分的账）。
 *
 * 玩家给的四个数，逐条：
 *
 *   ● ● ● ●        4 色 0 星   max(4,4) =  4    和从前一样
 *   ● ● ● ★        3 色 1 星   max(4,4) =  4    星星不消除，色块变星星
 *   ● ● ★ ★ ★    2 色 3 星   max(4,5) =  5    同上
 *   ★ ★ ★ ★      纯 4 星     4²       = 16
 *   ★ ★ ★ ★ ★    纯 5 星     5²       = 25    1×5
 *   ★×6（2×3 那一块） 纯 6 星  6²       = 36    平方的是**枚数**，不是边长
 *
 * ── 走过的弯路，写在这儿免得再走一遍 ────────────────────────────────────
 *
 * 定稿之前拿三种读法问过玩家（都满足「纯星星 = 枚数²」和「纯色块不变」这两个端
 * 点，只在混合那一格分岔）：
 *
 *   甲  max(4, 总枚数) − |S| + |S|²      2 色 3 星 → 11
 *   乙  max(4, 色块枚数) + |S|²          2 色 3 星 → 13
 *   丙  只要有星星就整组平方              2 色 3 星 → 25
 *
 * 玩家先说「按乙」，接着把真实规则给全了：混合组**一分都不变**（5 分），三种都
 * 不是。乙上线过几分钟就退回来了。真正的规则比三种都简单——星星只在**自己单独
 * 成图案**的时候才值钱。
 *
 * （丙当时还额外有个否掉的理由，留着有用：`●●●★` 会从 4 分跳到 16 分，玩家只
 * 要往任何图案里塞进一颗星星分就翻四倍，那是个刷分入口。现在的规则连这个口都没
 * 有——混合组塞星星一分不多。）
 *
 * ── 这个函数不管老虎机那套 ──────────────────────────────────────────────
 *
 * 老虎机模式（targets）的图案分是 `targets.ts` 的 `scoreOf`（`ceil(n²/2)`），
 * 走的是另一条路，这里一个字都不碰。
 */

/** 能得分的最小图案就是 4 格（1×4、2+2、1-2-1），所以 4 是色块那部分的地板。 */
export const MIN_GROUP_POINTS = 4;

/**
 * @param cells  这一组的全部格子
 * @param tileAt 拿某一格上的棋子；拿不到（越界、空位）按「不是星星」算
 */
export function groupPoints(
  cells: Cell[],
  tileAt: (r: number, c: number) => Tile | null | undefined,
): number {
  let stars = 0;
  for (const [r, c] of cells) {
    // 'dot' 就是界面上那颗星星（消过一次、翻过来的那一面）。'flavor' 是色块。
    if (tileAt(r, c)?.face === 'dot') stars++;
  }
  // 有色块 → 老规矩，一个数都不变。全是星星 → 枚数平方。
  const hasBlock = stars < cells.length;
  return hasBlock ? Math.max(MIN_GROUP_POINTS, cells.length) : stars * stars;
}
