import { createHash } from 'node:crypto';

/**
 * 日志里不写邮箱，写一枚短指纹。
 *
 * ── 原先是什么样 ──────────────────────────────────────────────
 *
 * `_accounts.js` 里四处「名单没删掉 / 名单没记上」、`updateAccount` 那句「锁忙」、
 * `mint.js` 的「这张码撤不回去了」、`redeem.js` 的「兑换记录没写上」——全都把邮箱
 * 原文（或者码原文）直接 `console.error` 出去。平时没人看，可那份日志在 Vercel
 * 后台留 30 天、任何拿到那个项目读权限的人都翻得到，而**我们从来没向玩家承诺过
 * 「你的邮箱会出现在运维日志里」**：隐私条款写的是「只存这几个字段」，日志这一份
 * 不在那张清单上。一条和实际行为不符的隐私陈述，支付审核按 false information 算。
 *
 * 更实际的一面：这些 `console.error` 恰好都挂在**出错**的那条路上，而出错的时候
 * 人是最可能把整段日志贴进工单、贴进对话、贴进 issue 的。一次手滑就是一串真实
 * 邮箱外泄。
 *
 * ── 为什么是 sha256 前 12 位，而不是「打星号」 ────────────────
 *
 * 日志唯一的用处是**对账**：同一个人在两分钟里报了三条错，得看得出那是同一个人；
 * 另一个人的一条，得看得出是另一个人。`a***@gmail.com` 这种打星号的写法把两件事
 * 都做坏了——同一个域名下所有首字母相同的人长得一模一样，而首字母和域名又恰好是
 * 猜一个邮箱最有用的那两样。
 *
 * 指纹反过来：外人从 12 个十六进制字符里拿不回邮箱（没有可逆的路，只能拿一份邮箱
 * 表来撞——那他本来就有那份表了），而我们自己要找某个具体的人时，算一遍他的指纹
 * 去 grep 就行。48 bit 够用：同一天的日志里撞号的概率可以忽略。
 *
 * 不加盐，正是为了这一句「算一遍去 grep」能成立。盐一加，查一个人要先知道那天的
 * 盐是什么，而这份日志的全部价值就是能查。
 *
 * ⚠️ **不要拿它当 key、当 id、当凭据。** 它只用来往日志里写一行字。账号的 key 是
 * `acct:<邮箱>`，免邮箱那种是 `pairKey`（那一个是 sha256 全长，而且有 `hdl:` 前缀，
 * 和这里不是一回事，别互相替用）。
 *
 * ⚠️ **兑换码那一处例外，`redeem.js:102` 的「兑换码放不回去了」仍然写原文**，有意
 * 的：那一行是一张**已经从库里拿走、却没放回去**的码的唯一下落——玩家付了钱、码
 * 烧掉了、权益没到账，这时候我们得凭日志把那张码找回来手工补给他。指纹找不回码，
 * 而码本身不是个人信息。那一行旁边也写着这件事。
 */
export const redact = (value) => {
  const s = String(value ?? '');
  if (!s) return '(空)';
  return createHash('sha256').update(s, 'utf8').digest('hex').slice(0, 12);
};
