/**
 * 两副小球棋盘「一颗球画在屏幕哪儿」的算式，和挂在这上面的三张偏移表。
 *
 * ── 为什么要单独有这个文件 ────────────────────────────────────────
 *
 * 六边小球（circleHex）和七色小球（circleSeven）各有各的坐标系，格子编号
 * (r,c) 走到屏幕上的算式两副不一样。而「2+2」「1-2-1」这些得分图案是照屏幕
 * 上看着的样子定的——它得画成一个菱形，不是随便四颗连一串。
 *
 * 这里出过一次真事：这两副的偏移表最早是照基础小球（circle.ts）那份原样抄
 * 过来的，想当然以为「一个用 (r,c) 步子写的形状，换块棋盘也还是那个形状」。
 * 不是的。circle.ts 的 (r,c) 是另外两个屏幕方向，同一串偏移搬到这两副上重放
 * 出来是一条拐来拐去的四连，根本不是菱形。结果是：玩家照着提示图凑出来的那
 * 个 2+2 不给分，倒是一个提示图里从来没出现过的形状在给分。
 *
 * 所以这两样东西——偏移表、和把格子换算成屏幕坐标的那个算式——必须待在一
 * 处，而且必须是玩法本体真正在用的那一份：体检脚本
 * （scripts/check-ball-offsets.mjs）拿它们当场画一遍，量出来不是菱形就报红。
 * 从前脚本里照着抄一份副本来量是不行的，抄本永远是过的。
 */

/**
 * 六边小球：一颗球相对棋盘原点的屏幕位置。
 *
 * 用的是立方坐标 (x, z)（见 circleHex 的 localToCube）——这副棋盘按行裁过，
 * 每一行的起始列都不一样，拿 (r,c) 直接做偏移会悄悄取到别的球上去。
 *
 * rowH 一律是 R·√3（正六边形排布的行高）。
 */
export function hexBallXY(x: number, z: number, R: number, rowH: number): [number, number] {
  return [2 * R * x + R * z, rowH * z];
}

/**
 * 七色小球：一颗球相对棋盘原点的屏幕位置（还没算菱形躺倒的那一下旋转）。
 *
 * 这副是正菱形排布：往右下一格 x 加 R，往左下一格 x 减 R，两种都往下 rowH。
 */
export function sevenBallXY(r: number, c: number, R: number, rowH: number): [number, number] {
  return [(c - r) * R, (r + c) * rowH];
}

/** 六边小球的偏移一律写成 (dz, dx)：先说往下几行，再说立方坐标的 x 走几步。 */
export type HexOffset = [number, number];

/** 靠右歪的那个菱形。 */
export const HEX_RHOMBUS_B_OFFSETS: HexOffset[] = [[0, 0], [0, 1], [1, 0], [1, 1]];

/** 靠左歪的那个菱形：由 (0,+1) 和 (+1,−1) 两个方向张开。 */
export const HEX_RHOMBUS_A_OFFSETS: HexOffset[] = [[0, 0], [0, 1], [1, -1], [1, 0]];

/** 正立的那个菱形，也就是提示图里的「1-2-1」：上一颗、中间两颗、下一颗。 */
export const HEX_DIAMOND_121_OFFSETS: HexOffset[] = [[0, 0], [1, -1], [1, 0], [2, -1]];

/**
 * 七色小球的「两组挨着的一对」，写成两个基向量。
 *
 * 这副格子有三个方向，两两之间都是一颗球的距离：(0,+1)、(+1,0)、(+1,−1)。
 * 任取两个张开就是一个菱形，所以正好三种朝向——正立一个、左右各歪一个。三
 * 个是同一个形状转过来的，所以三个都算分。
 */
export const SEVEN_RHOMBI: [[number, number], [number, number]][] = [
  [[0, 1], [1, 0]], //  正立的那个（提示图里的「1-2-1」）
  [[0, 1], [1, -1]], // 歪向一边  } 这两个合起来是提示图里的「2+2」
  [[1, 0], [1, -1]], // 歪向另一边 }
];
