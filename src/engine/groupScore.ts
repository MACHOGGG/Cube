import type { Cell, Tile } from './types';

/**
 * 一组图案值几分——**只有《无限反转》还在问这个函数**。
 *
 * 《侵蚀阶梯》v1.2 §1.2 之后，别的玩法的计分不再按「一组值几分」算，而是按
 * **这一步翻了几枚**算：每翻一枚 +2，同一步同一枚只算一次（见 scoring.ts 的
 * createCascadeStepper——它拿的是这一拍要翻的那个去重集合，不是各组的 points 之
 * 和）。所以那条路上这个函数的返回值根本没人看。
 *
 * 无限反转是例外（玩家 2026-09-27 拍板：「图案跟着变 1×N，但不吃侵蚀，计分保留
 * 它自己那一套」）：那一局翻过去还能翻回来，按翻面枚数计分会变成「来回翻刷
 * 分」，所以它照旧按组给分，外面再乘它自己的 1.5ⁿ 连锁（见 flipStreakDelta）。
 *
 * ── 退役的那一支 ────────────────────────────────────────────────────────
 * 这儿原先还有一条「整组都是星星 → 枚数²、并且从棋盘上消除」（《星星跟随色块消
 * 除》）。《侵蚀阶梯》把它整条废了：纯星星的线**无事发生**，不得分也不消除
 * （§1.1）。星星的去处改成了整线消除（§3），那是另一条路，不经过这儿。
 */

/** 能得分的最小图案就是 4 格，所以 4 是地板。 */
export const MIN_GROUP_POINTS = 4;

/**
 * @param cells  这一组的全部格子
 * @param tileAt 拿某一格上的棋子；拿不到（越界、空位）按「不是星星」算
 */
export function groupPoints(cells: Cell[], _tileAt: (r: number, c: number) => Tile | null | undefined): number {
  return Math.max(MIN_GROUP_POINTS, cells.length);
}
